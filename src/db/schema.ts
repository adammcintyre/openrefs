export const aiSnapshots = sqliteTable(
  "ai_snapshots",
  {
    id: id(),
    promptId: text("prompt_id")
      .notNull()
      .references(() => aiPrompts.id, { onDelete: "cascade" }),
    /** ISO date, `YYYY-MM-DD`. */
    date: text("date").notNull(),
    engine: text("engine").notNull(),
    mentioned: integer("mentioned", { mode: "boolean" }).notNull().default(false),
    /**
     * Stored rather than derived from `citations_json`.
     *
     * Citation rate is a `SUM(cited)` over a date range — the same shape as
     * mention rate — and deriving it would mean pulling every citation array
     * out of D1 and JSON-parsing it in the Worker to count booleans. One
     * indexed column instead of that, written by the same matcher run that
     * writes `citations_json`, so the two can never disagree.
     */
    cited: integer("cited", { mode: "boolean" }).notNull().default(false),
    citationsJson: text("citations_json", { mode: "json" })
      .$type<AiCitation[]>()
      .notNull()
      .default(sql`'[]'`),
    /**
     * Up to 2000 characters of the answer, centred on the mention. The full
     * response goes to R2 at `ws:<workspaceId>/ai/<snapshotId>.json`; this is
     * what the drill-down renders without a blob fetch.
     */
    responseExcerpt: text("response_excerpt").notNull().default(""),
    /**
     * The model that actually answered, as DataForSEO resolved it — a bare
     * `gpt-4o-mini` comes back as `gpt-4o-mini-2024-07-18`. Provenance: a
     * mention rate is only comparable across weeks if the same model produced
     * it, and the model behind an engine id changes without our involvement.
     */
    model: text("model"),
    /**
     * What this one answer cost, USD.
     *
     * Recorded per snapshot because this family's price is not knowable in
     * advance — DataForSEO's fee plus whatever the LLM provider charged for
     * the tokens and the web search (see src/shared/ai.ts). `api_usage` has
     * the workspace total; this is what lets the UI say what a *run* cost.
     */
    costUsd: real("cost_usd").notNull().default(0),
    createdAt: createdAt(),
  },
  (t) => [
    /*
     * One row per prompt per engine per day, enforced rather than hoped for —
     * the same bargain rank_snapshots makes. The runner upserts on this
     * conflict, so pressing "Run now" twice in an afternoon refreshes the day's
     * answer instead of appending a second row that would silently double that
     * day's weight in the mention rate.
     */
    uniqueIndex("ai_snapshots_prompt_engine_date_idx").on(
      t.promptId,
      t.engine,
      t.date,
    ),
    // The results query scans one prompt across a date range.
    index("ai_snapshots_prompt_date_idx").on(t.promptId, t.date),
  ],
);

