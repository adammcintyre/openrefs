export const collectionKeywords = sqliteTable(
  "collection_keywords",
  {
    collectionId: text("collection_id")
      .notNull()
      .references(() => collections.id, { onDelete: "cascade" }),
    keyword: text("keyword").notNull(),
    /** Search volume at the moment it was saved, so lists stay comparable. */
    volumeSnapshot: integer("volume_snapshot"),
    addedAt: integer("added_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  (t) => [
    primaryKey({ columns: [t.collectionId, t.keyword] }),
    index("collection_keywords_collection_id_idx").on(t.collectionId),
  ],
);

/* -------------------------------------------------------------------------- */
/* Rank tracking                                                               */
/* -------------------------------------------------------------------------- */

export const trackedKeywords = sqliteTable(
  "tracked_keywords",
  {
    id: id(),
    projectId: text("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    keyword: text("keyword").notNull(),
    locationCode: integer("location_code").notNull(),
    languageCode: text("language_code").notNull(),
    device: text("device", { enum: DEVICES }).notNull().default("desktop"),
    createdAt: createdAt(),
  },
  (t) => [
    index("tracked_keywords_project_id_idx").on(t.projectId),
    uniqueIndex("tracked_keywords_unique_idx").on(
      t.projectId,
      t.keyword,
      t.locationCode,
      t.languageCode,
      t.device,
    ),
  ],
);

export const rankSnapshots = sqliteTable(
  "rank_snapshots",
  {
    id: id(),
    trackedKeywordId: text("tracked_keyword_id")
      .notNull()
      .references(() => trackedKeywords.id, { onDelete: "cascade" }),
    /** ISO date, `YYYY-MM-DD`, so daily series group without timezone maths. */
    date: text("date").notNull(),
    /** Null means "not in the fetched results" — distinct from position 100. */
    position: integer("position"),
    url: text("url"),
    serpFeaturesJson: text("serp_features_json", { mode: "json" })
      .$type<string[]>()
      .notNull()
      .default(sql`'[]'`),
    createdAt: createdAt(),
  },
  (t) => [
    // The history chart's only query shape: one keyword, ordered by date.
    index("rank_snapshots_keyword_date_idx").on(t.trackedKeywordId, t.date),
  ],
);

