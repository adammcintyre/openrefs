/* Search Console                                                              */
/* -------------------------------------------------------------------------- */

export const gscConnections = sqliteTable("gsc_connections", {
  /** One connection per project, so the project id is the key. */
  projectId: text("project_id")
    .primaryKey()
    .references(() => projects.id, { onDelete: "cascade" }),
  /** Google refresh token, AES-256-GCM encrypted with APP_MASTER_KEY. */
  refreshTokenEnc: text("refresh_token_enc").notNull(),
  /** GSC property URL, e.g. "sc-domain:example.com". */
  property: text("property").notNull(),
  /** Kept if the connecting user is later deleted — the project keeps its data. */
  connectedBy: text("connected_by").references(() => users.id, {
    onDelete: "set null",
  }),
  createdAt: createdAt(),
});

