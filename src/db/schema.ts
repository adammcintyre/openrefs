export const workspaces = sqliteTable("workspaces", {
  id: id(),
  name: text("name").notNull(),
  /**
   * DataForSEO credentials, AES-256-GCM encrypted with APP_MASTER_KEY in the
   * `v1$iv$ciphertext` format from src/worker/lib/crypto.ts. Never selected
   * into an API response.
   */
  dfsLoginEnc: text("dfs_login_enc"),
  dfsPasswordEnc: text("dfs_password_enc"),
  /**
   * Monthly ceiling in USD enforced by the DataForSEO client before it spends.
   * 0 blocks every paid call; cached reads are always allowed.
   */
  spendCapUsd: real("spend_cap_usd").notNull().default(25),
  settingsJson: text("settings_json", { mode: "json" })
    .$type<Record<string, unknown>>()
    .notNull()
    .default(sql`'{}'`),
  createdAt: createdAt(),
});

