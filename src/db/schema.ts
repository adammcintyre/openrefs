/**
 * OpenRefs D1 schema (Drizzle / SQLite).
 *
 * Two invariants hold across this file and MUST hold for anything added later:
 *
 * 1. Deletion is a feature. Every table holding workspace data is reachable
 *    from `workspaces` by a chain of `onDelete: "cascade"` foreign keys, so
 *    deleting a workspace row empties D1 of that tenant. KV and R2 are purged
 *    separately by prefix (`ws:<workspaceId>:` / `ws:<workspaceId>/`).
 * 2. Column names are written out explicitly in snake_case rather than relying
 *    on a `casing` setting, so drizzle-kit and the runtime client can never
 *    disagree about what a column is called.
 *
 * SQLite enforces foreign keys only when `PRAGMA foreign_keys = ON`. D1 sets
 * this for you; `wrangler d1 execute` sessions do not always.
 */
import { relations, sql } from "drizzle-orm";
import {
  index,
  integer,
  primaryKey,
  real,
  sqliteTable,
  text,
  uniqueIndex,
} from "drizzle-orm/sqlite-core";

/** Text primary key, defaulted to a UUID v4 generated by WebCrypto. */
const id = () =>
  text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID());

/** Epoch milliseconds, defaulted to insert time. */
const createdAt = () =>
  integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date());

export const WORKSPACE_ROLES = ["owner", "admin", "member"] as const;
export type WorkspaceRole = (typeof WORKSPACE_ROLES)[number];

export const JOB_STATUSES = ["pending", "running", "done", "failed"] as const;
export type JobStatus = (typeof JOB_STATUSES)[number];

export const AUDIT_STATUSES = [
  "pending",
  "running",
  "done",
  "failed",
] as const;
export type AuditStatus = (typeof AUDIT_STATUSES)[number];

export const DEVICES = ["desktop", "mobile"] as const;
export type Device = (typeof DEVICES)[number];

/* -------------------------------------------------------------------------- */
/* Identity                                                                    */
/* -------------------------------------------------------------------------- */

export const users = sqliteTable("users", {
  id: id(),
  email: text("email").notNull().unique(),
  /** PBKDF2-SHA256, 600k iterations. Format owned by the auth module. */
  passwordHash: text("password_hash").notNull(),
  createdAt: createdAt(),
});

export const sessions = sqliteTable(
  "sessions",
  {
    /** Opaque session id; the cookie carries this value. */
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [
    // Hot path: "log this user out everywhere" and session cleanup.
    index("sessions_user_id_idx").on(t.userId),
    index("sessions_expires_at_idx").on(t.expiresAt),
  ],
);

/* -------------------------------------------------------------------------- */
/* Workspaces                                                                  */
/* -------------------------------------------------------------------------- */

export const workspaces = sqliteTable("workspaces", {
  id: id(),
  name: text("name").notNull(),
  /**
   * DataForSEO credentials, AES-256-GCM encrypted with APP_MASTER_KEY in the
   * `v1$iv$ciphertext` format from src/worker/lib/crypto.ts. Never selected
   * into an API response.
   */
  dfsLoginEnc: text("dfs_login_enc"),
  dfsPasswordEnc: text("dfs_password_enc"),
  /**
   * Monthly ceiling in USD enforced by the DataForSEO client before it spends.
   * 0 blocks every paid call; cached reads are always allowed.
   */
  spendCapUsd: real("spend_cap_usd").notNull().default(25),
  settingsJson: text("settings_json", { mode: "json" })
    .$type<Record<string, unknown>>()
    .notNull()
    .default(sql`'{}'`),
  createdAt: createdAt(),
});

export const workspaceMembers = sqliteTable(
  "workspace_members",
  {
    workspaceId: text("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    role: text("role", { enum: WORKSPACE_ROLES }).notNull().default("member"),
    createdAt: createdAt(),
  },
  (t) => [
    primaryKey({ columns: [t.workspaceId, t.userId] }),
    // Both directions are hot: "who is in this workspace" and the
    // workspace-switcher's "what can this user see".
    index("workspace_members_workspace_id_idx").on(t.workspaceId),
    index("workspace_members_user_id_idx").on(t.userId),
  ],
);

export const invites = sqliteTable(
  "invites",
  {
    id: id(),
    workspaceId: text("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    email: text("email").notNull(),
    /** SHA-256 of the invite token. The raw token only ever exists in the link. */
    tokenHash: text("token_hash").notNull().unique(),
    role: text("role", { enum: WORKSPACE_ROLES }).notNull().default("member"),
    expiresAt: integer("expires_at", { mode: "timestamp_ms" }).notNull(),
    createdAt: createdAt(),
  },
  (t) => [index("invites_workspace_id_idx").on(t.workspaceId)],
);

export const apiKeys = sqliteTable(
  "api_keys",
  {
    id: id(),
    workspaceId: text("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    /** SHA-256 of the key. The plaintext is shown once, at creation. */
    keyHash: text("key_hash").notNull().unique(),
    createdAt: createdAt(),
    lastUsedAt: integer("last_used_at", { mode: "timestamp_ms" }),
  },
  (t) => [index("api_keys_workspace_id_idx").on(t.workspaceId)],
);

/* -------------------------------------------------------------------------- */
/* Projects (a site you own)                                                   */
/* -------------------------------------------------------------------------- */

export const projects = sqliteTable(
  "projects",
  {
    id: id(),
    workspaceId: text("workspace_id")
      .notNull()
      .references(() => workspaces.id, { onDelete: "cascade" }),
    /** Bare hostname, no scheme, e.g. "example.com". */
    domain: text("domain").notNull(),
    name: text("name").notNull(),
    /** DataForSEO location/language codes. Defaults are UK / English. */
    locationCode: integer("location_code").notNull().default(2826),
    languageCode: text("language_code").notNull().default("en"),
    settingsJson: text("settings_json", { mode: "json" })
      .$type<Record<string, unknown>>()
      .notNull()
      .default(sql`'{}'`),
    createdAt: createdAt(),
  },
  (t) => [index("projects_workspace_id_idx").on(t.workspaceId)],
);

