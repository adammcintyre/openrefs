/**
 * OpenRefs D1 schema (Drizzle / SQLite).
 *
 * Two invariants hold across this file and MUST hold for anything added later:
 *
 * 1. Deletion is a feature. Every table holding workspace data is reachable
 *    from `workspaces` by a chain of `onDelete: "cascade"` foreign keys, so
 *    deleting a workspace row empties D1 of that tenant. KV and R2 are purged
 *    separately by prefix (`ws:<workspaceId>:` / `ws:<workspaceId>/`).
 * 2. Column names are written out explicitly in snake_case rather than relying
 *    on a `casing` setting, so drizzle-kit and the runtime client can never
 *    disagree about what a column is called.
 *
 * SQLite enforces foreign keys only when `PRAGMA foreign_keys = ON`. D1 sets
 * this for you; `wrangler d1 execute` sessions do not always.
 */
import { relations, sql } from "drizzle-orm";
import {
  index,
  integer,
  primaryKey,
  real,
  sqliteTable,
  text,
  uniqueIndex,
} from "drizzle-orm/sqlite-core";

import type { AiCitation } from "../shared/ai";

/** Text primary key, defaulted to a UUID v4 generated by WebCrypto. */
const id = () =>
  text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID());

/** Epoch milliseconds, defaulted to insert time. */
const createdAt = () =>
  integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date());

export const WORKSPACE_ROLES = ["owner", "admin", "member"] as const;
export type WorkspaceRole = (typeof WORKSPACE_ROLES)[number];

export const JOB_STATUSES = ["pending", "running", "done", "failed"] as const;
export type JobStatus = (typeof JOB_STATUSES)[number];

export const AUDIT_STATUSES = [
  "pending",
  "running",
  "done",
  "failed",
] as const;
export type AuditStatus = (typeof AUDIT_STATUSES)[number];

export const DEVICES = ["desktop", "mobile"] as const;
export type Device = (typeof DEVICES)[number];

