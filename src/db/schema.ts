/* -------------------------------------------------------------------------- */
/* Relations                                                                   */
/* -------------------------------------------------------------------------- */

export const usersRelations = relations(users, ({ many }) => ({
  sessions: many(sessions),
  memberships: many(workspaceMembers),
}));

export const sessionsRelations = relations(sessions, ({ one }) => ({
  user: one(users, { fields: [sessions.userId], references: [users.id] }),
}));

export const workspacesRelations = relations(workspaces, ({ many }) => ({
  members: many(workspaceMembers),
  invites: many(invites),
  apiKeys: many(apiKeys),
  projects: many(projects),
  collections: many(collections),
  apiUsage: many(apiUsage),
  jobs: many(jobs),
}));

export const workspaceMembersRelations = relations(
  workspaceMembers,
  ({ one }) => ({
    workspace: one(workspaces, {
      fields: [workspaceMembers.workspaceId],
      references: [workspaces.id],
    }),
    user: one(users, {
      fields: [workspaceMembers.userId],
      references: [users.id],
    }),
  }),
);

export const projectsRelations = relations(projects, ({ one, many }) => ({
  workspace: one(workspaces, {
    fields: [projects.workspaceId],
    references: [workspaces.id],
  }),
  trackedKeywords: many(trackedKeywords),
  audits: many(audits),
  aiPrompts: many(aiPrompts),
}));

export const collectionsRelations = relations(collections, ({ one, many }) => ({
  workspace: one(workspaces, {
    fields: [collections.workspaceId],
    references: [workspaces.id],
  }),
  keywords: many(collectionKeywords),
}));

export const collectionKeywordsRelations = relations(
  collectionKeywords,
  ({ one }) => ({
    collection: one(collections, {
      fields: [collectionKeywords.collectionId],
      references: [collections.id],
    }),
  }),
);

export const trackedKeywordsRelations = relations(
  trackedKeywords,
  ({ one, many }) => ({
    project: one(projects, {
      fields: [trackedKeywords.projectId],
      references: [projects.id],
    }),
    snapshots: many(rankSnapshots),
  }),
);

export const rankSnapshotsRelations = relations(rankSnapshots, ({ one }) => ({
  trackedKeyword: one(trackedKeywords, {
    fields: [rankSnapshots.trackedKeywordId],
    references: [trackedKeywords.id],
  }),
}));

export const aiPromptsRelations = relations(aiPrompts, ({ one, many }) => ({
  project: one(projects, {
    fields: [aiPrompts.projectId],
    references: [projects.id],
  }),
  snapshots: many(aiSnapshots),
}));

export const aiSnapshotsRelations = relations(aiSnapshots, ({ one }) => ({
  prompt: one(aiPrompts, {
    fields: [aiSnapshots.promptId],
    references: [aiPrompts.id],
  }),
}));
