/* Background work (cron + this table; no Queues, no Durable Objects)          */
/* -------------------------------------------------------------------------- */

export const jobs = sqliteTable(
  "jobs",
  {
    id: id(),
    /** Discriminator owned by the job handlers, e.g. "rank_check". */
    type: text("type").notNull(),
    /**
     * Nullable so housekeeping jobs can exist without a tenant. When set, the
     * cascade guarantees a deleted workspace leaves no queued work behind —
     * this column exists for that reason and must be populated by any job
     * that touches workspace data.
     */
    workspaceId: text("workspace_id").references(() => workspaces.id, {
      onDelete: "cascade",
    }),
    payloadJson: text("payload_json", { mode: "json" })
      .$type<Record<string, unknown>>()
      .notNull()
      .default(sql`'{}'`),
    /** Earliest time the sweeper may pick this up. Doubles as the retry backoff. */
    runAt: integer("run_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),
    status: text("status", { enum: JOB_STATUSES }).notNull().default("pending"),
    attempts: integer("attempts").notNull().default(0),
    lastError: text("last_error"),
    createdAt: createdAt(),
  },
  (t) => [
    // The sweeper's only query: pending jobs whose run_at has passed.
    index("jobs_status_run_at_idx").on(t.status, t.runAt),
    index("jobs_workspace_id_idx").on(t.workspaceId),
  ],
);

